#!/usr/bin/env node

// Generates skill reference files from the Neon docs. Each file in SKILL_DOCS
// is the website's agent-ready markdown for one docs page (the same output
// neon.com serves at /docs/<page>.md), with the navigation header and feedback
// footer stripped, links rewritten so they work from inside the skill, and a
// table of contents added. A header comment records the source and a hash of
// the body, so a hand edit fails the check.
//
// TODO: The pages aren't live on neon.com yet, so the only source is a local
// checkout of the website repo. Adding a neon.com source (and a scheduled
// refresh) is a follow-up for after the docs launch.
//
// Usage:
//   node scripts/sync-skill-docs.mjs --website ../website   # regenerate
//   node scripts/sync-skill-docs.mjs --check                # verify, offline

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";

// Which docs pages each skill vendors, keyed by skill directory name under
// skills/. Each entry maps a file in skills/<skill>/references/ to a docs page
// path (no leading slash, no extension).
const SKILL_DOCS = {
  "neon-realtime": {
    "queries.md": "docs/realtime/guides/queries",
    "subscribing.md": "docs/realtime/guides/subscribing",
    "reactivity.md": "docs/realtime/guides/reactivity",
    "mutations.md": "docs/realtime/guides/mutations",
    "ssr.md": "docs/realtime/guides/ssr",
  },
};

const SITE = "https://neon.com";
const CONVERTER = "src/scripts/process-md-for-llms.js";
const HEADER_RE =
  /^<!-- Generated by scripts\/sync-skill-docs\.mjs from (\S+) \((\S+)\)\. Do not edit: change the docs and run npm run sync:docs\. sha256:([0-9a-f]{64}) -->\n/;

const repoRoot = process.cwd();
const skillsRoot = path.join(repoRoot, "skills");
const pluginsRoot = path.join(repoRoot, "plugins");

const args = process.argv.slice(2);
const checkMode = args.includes("--check");
const websiteIndex = args.indexOf("--website");
const websiteArg = websiteIndex === -1 ? null : args[websiteIndex + 1];
const problems = [];

function fail(message) {
  problems.push(message);
}

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

async function pathExists(targetPath) {
  try {
    await fs.access(targetPath);
    return true;
  } catch {
    return false;
  }
}

// Splits markdown into lines tagged with whether they sit inside a fenced
// code block (fence lines included), so transforms leave code untouched.
function tagLines(markdown) {
  let fence = null;
  return markdown.split("\n").map((line) => {
    const match = line.match(/^\s*(`{3,}|~{3,})/);
    if (fence) {
      if (
        match &&
        match[1][0] === fence[0] &&
        match[1].length >= fence.length
      ) {
        fence = null;
      }
      return { line, code: true };
    }
    if (match) {
      fence = match[1];
      return { line, code: true };
    }
    return { line, code: false };
  });
}

// Replaces each markdown link target in a line with `fn(target)`. Scanning
// matches inline code spans too, so links shown as code are left alone, while
// link text may itself contain code, e.g. [`useLiveQuery`](../sdks/typescript).
const LINK_OR_CODE_RE =
  /(`+)[^`]*?\1|(!?\[(?:`[^`]*`|[^\]`])*\]\()([^)\s]+)((?:\s+"[^"]*")?\))/g;

function replaceLinks(line, fn) {
  return line.replace(LINK_OR_CODE_RE, (whole, _code, open, target, close) =>
    open ? `${open}${fn(target)}${close}` : whole,
  );
}

function unwrapLinks(text) {
  return text.replace(/!?\[((?:`[^`]*`|[^\]`])*)\]\([^)]*\)/g, "$1");
}

// GitHub-style heading slug: lowercase, drop punctuation (keeping letters,
// numbers, underscores, hyphens and spaces), spaces to hyphens. Duplicate
// slugs get -1, -2, ... like GitHub.
function headingText(raw) {
  return unwrapLinks(raw).replace(/`/g, "").replace(/\*+/g, "").trim();
}

function slugify(text) {
  return headingText(text)
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");
}

function headings(markdown) {
  const seen = new Map();
  const result = [];
  for (const { line, code } of tagLines(markdown)) {
    const match = !code && line.match(/^(#{1,6})\s+(.+?)\s*#*\s*$/);
    if (!match) {
      continue;
    }
    const base = slugify(match[2]);
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    result.push({
      level: match[1].length,
      text: match[2],
      slug: count === 0 ? base : `${base}-${count}`,
    });
  }
  return result;
}

// 1. Strip the index/location header and the related-docs and feedback
// footers, using the same patterns as the converter's stripNavigationContext().
function stripNavigation(markdown, docPath) {
  let stripped = markdown.replace(
    /^(?:> This page location:[^\n]*\n)?> Full Neon documentation index:[^\n]*\n(?:>\n> Agent skills:[^\n]*\n)?(?:> IMPORTANT: If this page[^\n]*\n)?\n/,
    "",
  );
  stripped = stripped.replace(
    /\n---\n\n## Related docs \([^)]*\)\n[\s\S]*$/,
    "\n",
  );
  stripped = stripped.replace(
    /\n---\n\n(?:Note for AI assistants|If this page contains inaccurate)[\s\S]*$/,
    "\n",
  );
  if (/Full Neon documentation index|Note for AI assistants/.test(stripped)) {
    fail(
      `${docPath}: converter header or footer not stripped (format changed?)`,
    );
  }
  return `${stripped.trimEnd()}\n`;
}

// 2. Rewrite links outside code so they work from skills/<skill>/references/.
function rewriteLinks(markdown, docPath, vendored) {
  const pageUrl = new URL(`${SITE}/${docPath}`);
  const rewrite = (target) => {
    let url;
    try {
      url = new URL(target, pageUrl);
    } catch {
      return target;
    }
    if (url.origin !== SITE) {
      return target;
    }
    const page = url.pathname.replace(/\/$/, "");
    if (page === pageUrl.pathname && !url.search) {
      return url.hash || "#";
    }
    if (vendored.has(page) && !url.search) {
      return `${vendored.get(page)}${url.hash}`;
    }
    if (page.startsWith("/docs/") && !path.extname(page)) {
      return `${SITE}${page}.md${url.search}${url.hash}`;
    }
    return /^[a-z][a-z0-9+.-]*:/i.test(target) ? target : url.href;
  };
  return tagLines(markdown)
    .map(({ line, code }) => (code ? line : replaceLinks(line, rewrite)))
    .join("\n");
}

// 3. Insert a two-level table of contents after the H1 and its subtitle.
function addContents(markdown, docPath) {
  const items = headings(markdown)
    .filter(({ level }) => level === 2 || level === 3)
    .map(
      ({ level, text, slug }) =>
        `${level === 3 ? "  " : ""}- [${unwrapLinks(text)}](#${slug})`,
    );
  const lines = markdown.split("\n");
  const h1 = lines.findIndex((line) => /^# /.test(line));
  if (h1 === -1 || items.length === 0) {
    fail(`${docPath}: no H1 or no ##/### headings to build contents from`);
    return markdown;
  }
  let at = h1 + 1;
  while (at < lines.length && lines[at].trim() === "") at++;
  while (at < lines.length && lines[at].trim() !== "") at++;
  lines.splice(at, 0, "", "## Contents", "", ...items);
  return lines.join("\n");
}

// 4. Prepend the generated-file header and the canonical page line.
function addHeader(body, source, docPath) {
  const full = `Canonical page: ${SITE}/${docPath}.md\n\n${body}`;
  return `<!-- Generated by scripts/sync-skill-docs.mjs from ${source} (${docPath}). Do not edit: change the docs and run npm run sync:docs. sha256:${sha256(full)} -->\n${full}`;
}

// Every #anchor must match a heading in the file, and every <file>.md#anchor
// must match a heading in that vendored file.
function checkAnchors(skill, files) {
  const slugs = new Map(
    Object.entries(files).map(([file, content]) => [
      file,
      new Set(headings(content).map(({ slug }) => slug)),
    ]),
  );
  for (const [file, content] of Object.entries(files)) {
    for (const { line, code } of tagLines(content)) {
      if (code) continue;
      replaceLinks(line, (target) => {
        const match = target.match(/^([\w.-]+\.md)?#(.+)$/);
        const targetFile = match && (match[1] ?? file);
        if (
          match &&
          slugs.has(targetFile) &&
          !slugs.get(targetFile).has(match[2])
        ) {
          fail(
            `skills/${skill}/references/${file}: link ${target} has no matching heading in ${targetFile}`,
          );
        }
        return target;
      });
    }
  }
}

// The generated files must be excluded from prettier (including their plugin
// copies), or `npm run fmt` would reformat them and break their hashes.
async function checkPrettierIgnored(skill, file) {
  let prettier;
  try {
    prettier = await import("prettier");
  } catch {
    fail('prettier is not installed (run "npm ci --ignore-scripts")');
    return;
  }
  const targets = [path.join("skills", skill, "references", file)];
  if (await pathExists(pluginsRoot)) {
    for (const plugin of await fs.readdir(pluginsRoot)) {
      if (await pathExists(path.join(pluginsRoot, plugin, "skills", skill))) {
        targets.push(
          path.join("plugins", plugin, "skills", skill, "references", file),
        );
      }
    }
  }
  for (const target of targets) {
    const { ignored } = await prettier.getFileInfo(target, {
      ignorePath: [".gitignore", ".prettierignore"],
    });
    if (!ignored) {
      fail(`${target} is generated but not excluded in .prettierignore`);
    }
  }
}

function websiteSource(websiteDir, docPaths) {
  const git = (...gitArgs) =>
    execFileSync("git", ["-C", websiteDir, ...gitArgs], {
      encoding: "utf8",
    }).trim();
  const branch = git("rev-parse", "--abbrev-ref", "HEAD");
  const sha = git("rev-parse", "--short", "HEAD");
  const dirty = git(
    "status",
    "--porcelain",
    "--",
    ...docPaths.map((docPath) => `content/${docPath}.md`),
  );
  return `website@${branch}:${sha}${dirty ? "+dirty" : ""}`;
}

async function generate(websiteDir, skill, docs) {
  const vendored = new Map(
    Object.entries(docs).map(([file, docPath]) => [`/${docPath}`, file]),
  );
  const source = websiteSource(websiteDir, Object.values(docs));
  const files = {};
  for (const [file, docPath] of Object.entries(docs)) {
    const input = path.join(websiteDir, "content", `${docPath}.md`);
    if (!(await pathExists(input))) {
      fail(`${skill}/${file}: docs page not found: ${input}`);
      continue;
    }
    const converted = execFileSync(
      process.execPath,
      [CONVERTER, "--file", path.join("content", `${docPath}.md`)],
      { cwd: websiteDir, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
    );
    let body = stripNavigation(converted, docPath);
    body = rewriteLinks(body, docPath, vendored);
    body = addContents(body, docPath);
    files[file] = addHeader(body, source, docPath);
  }
  return files;
}

async function readGenerated(skill, docs) {
  const files = {};
  for (const [file, docPath] of Object.entries(docs)) {
    const target = path.join(skillsRoot, skill, "references", file);
    if (!(await pathExists(target))) {
      fail(
        `Missing generated reference: skills/${skill}/references/${file} (run "npm run sync:docs -- --website ../website")`,
      );
      continue;
    }
    const content = await fs.readFile(target, "utf8");
    const header = content.match(HEADER_RE);
    if (!header) {
      fail(
        `skills/${skill}/references/${file}: missing or malformed generated header`,
      );
    } else if (header[2] !== docPath) {
      fail(
        `skills/${skill}/references/${file}: generated from ${header[2]}, but SKILL_DOCS maps it to ${docPath}`,
      );
    } else if (header[3] !== sha256(content.slice(header[0].length))) {
      fail(
        `skills/${skill}/references/${file}: content does not match its hash (hand-edited? change the docs and run "npm run sync:docs -- --website ../website")`,
      );
    }
    files[file] = content;
  }
  return files;
}

// Returns a generated file without its header line.
function bodyOf(content) {
  return content.replace(HEADER_RE, "");
}

async function main() {
  let websiteDir = null;
  if (!checkMode) {
    if (!websiteArg) {
      throw new Error(
        "Missing --website <dir>: pass a local checkout of the Neon website repo, e.g. npm run sync:docs -- --website ../website (or --check to verify).",
      );
    }
    websiteDir = path.resolve(websiteArg);
    if (!(await pathExists(path.join(websiteDir, CONVERTER)))) {
      throw new Error(
        `Not a Neon website checkout (no ${CONVERTER}): ${websiteDir}`,
      );
    }
  }

  for (const [skill, docs] of Object.entries(SKILL_DOCS)) {
    if (!(await pathExists(path.join(skillsRoot, skill, "SKILL.md")))) {
      fail(
        `SKILL_DOCS maps unknown skill "${skill}" (missing skills/${skill}).`,
      );
      continue;
    }
    const files = checkMode
      ? await readGenerated(skill, docs)
      : await generate(websiteDir, skill, docs);
    checkAnchors(skill, files);
    for (const file of Object.keys(docs)) {
      await checkPrettierIgnored(skill, file);
    }
    if (checkMode || problems.length > 0) {
      continue;
    }
    const referencesDir = path.join(skillsRoot, skill, "references");
    await fs.mkdir(referencesDir, { recursive: true });
    for (const [file, content] of Object.entries(files)) {
      const target = path.join(referencesDir, file);
      // Leave a file alone when only its source line would change, so
      // regenerating from a newer website commit doesn't churn unchanged pages.
      if (
        (await pathExists(target)) &&
        bodyOf(await fs.readFile(target, "utf8")) === bodyOf(content)
      ) {
        process.stderr.write(`Unchanged skills/${skill}/references/${file}\n`);
        continue;
      }
      await fs.writeFile(target, content);
      process.stderr.write(
        `Generated skills/${skill}/references/${file} from ${docs[file]}\n`,
      );
    }
  }

  if (problems.length > 0) {
    process.stderr.write(
      checkMode
        ? "Generated skill docs are out of sync:\n"
        : "Skill docs sync failed:\n",
    );
    for (const problem of problems) {
      process.stderr.write(`- ${problem}\n`);
    }
    process.exit(1);
  }

  process.stderr.write(
    checkMode ? "Generated skill docs are in sync.\n" : "Skill docs synced.\n",
  );
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
});
